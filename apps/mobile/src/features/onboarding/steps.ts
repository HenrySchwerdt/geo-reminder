import type { Href } from 'expo-router';

import type { LocationAccess } from '@/features/geofencing/permissions';

/** Onboarding steps in order (docs/product/user-flows.md, Flow 1). */
export const ONBOARDING_STEPS = ['welcome', 'hours', 'location', 'notifications', 'workplace', 'done'] as const;
export type OnboardingStep = (typeof ONBOARDING_STEPS)[number];

/** Route segment that holds the onboarding stack (`src/app/onboarding`). */
export const ONBOARDING_SEGMENT = 'onboarding';

/** Routes that may be open while onboarding is still pending: the stack itself and the workplace editor it opens. */
const ALLOWED_WHILE_PENDING: readonly string[] = [ONBOARDING_SEGMENT, 'workplace'];

// Typed routes are generated by `expo start`; cast so this file does not depend on a regenerated `.expo/types`.
export const stepHref = (step: OnboardingStep): Href => (step === 'welcome' ? '/onboarding' : `/onboarding/${step}`) as Href;
export const NEW_WORKPLACE_HREF = '/workplace/new' as Href;
export const TODAY_HREF = '/(tabs)' as Href;

export const stepIndex = (step: OnboardingStep) => ONBOARDING_STEPS.indexOf(step);

export function nextStep(step: OnboardingStep): OnboardingStep | null {
  return ONBOARDING_STEPS[stepIndex(step) + 1] ?? null;
}

export function previousStep(step: OnboardingStep): OnboardingStep | null {
  return ONBOARDING_STEPS[stepIndex(step) - 1] ?? null;
}

/** True when the app should send the user to onboarding: not finished yet and not already on an allowed route. */
export function shouldRedirectToOnboarding(onboarded: boolean, segments: readonly string[]): boolean {
  if (onboarded) return false;
  const root = segments[0];
  return root === undefined || !ALLOWED_WHILE_PENDING.includes(root);
}

export type LocationView = 'intro' | 'always' | 'whenInUse' | 'denied';

/**
 * Which panel the location step shows. The disclosure ("intro") is always shown first; the outcome panels only
 * replace it once the system prompts were answered, or when the OS already answered them for us.
 */
export function locationView(access: LocationAccess, requested: boolean): LocationView {
  if (access === 'always') return 'always';
  if (access === 'denied') return 'denied';
  if (requested && access === 'whenInUse') return 'whenInUse';
  return 'intro';
}
